using System.Text;
using AgentCrew.Core.Agents;
using AgentCrew.Core.Tools;

namespace AgentCrew.Core.Orchestration;

/// <summary>Собирает команду по умолчанию: планировщик, исследователь, аналитик, редактор, критик.</summary>
public static class CrewFactory
{
    public const string CompanyName = "ТехноЛавка";

    public static AgentCatalog CreateDefault(KnowledgeBase knowledgeBase, SalesData sales, CrewOptions? options = null, DateOnly? today = null)
    {
        options ??= new CrewOptions();
        var date = (today ?? DateOnly.FromDateTime(DateTime.Now)).ToString("dd.MM.yyyy");

        var researcher = new AgentDefinition
        {
            Id = "researcher",
            DisplayName = "Исследователь",
            Description = "ищет факты во внутренней базе знаний: стратегия, политики, рыночные отчёты, риски, маркетинг, логистика",
            Tools = [CrewTools.SearchKnowledgeBase(knowledgeBase), CrewTools.ListDocuments(knowledgeBase), CrewTools.ReadDocument(knowledgeBase)],
            VerifyGrounding = true,
            Instructions = Prompt("researcher", date, $"""
                Ты — агент-исследователь компании «{CompanyName}». Ты находишь факты во внутренней базе знаний с помощью инструментов.

                Как работать:
                - Всегда начинай с search_knowledge_base. Сделай 1–3 поиска с разными формулировками, если первого мало.
                - Если фрагмент обрывается или нужен контекст — прочитай документ целиком через read_document.
                - Не выдумывай. Если информации нет в базе — прямо так и напиши.
                - Передавай факты близко к тексту источника. Не связывай факты причинно, если источник этого не делает.
                - Следи за периодами: прогноз или возможность на следующий квартал — не причина того, что уже произошло.

                Формат ответа: краткий маркированный список фактов, у каждого — источник в формате [документ › раздел].
                """),
        };

        var analyst = new AgentDefinition
        {
            Id = "analyst",
            DisplayName = "Аналитик",
            Description = "считает показатели по данным продаж (выручка, динамика по кварталам, доли, возвраты по товарам и регионам)",
            Tools = [CrewTools.SalesReport(sales), CrewTools.CompareQuarters(sales), CrewTools.DataSchema(sales), CrewTools.Calculate()],
            VerifyGrounding = true,
            Instructions = Prompt("analyst", date, $"""
                Ты — агент-аналитик данных компании «{CompanyName}». У тебя есть доступ к данным продаж через инструменты.

                Как работать:
                - Если не уверен, какие есть кварталы/регионы/товары — вызови describe_sales_data.
                - Все числа бери только из результатов инструментов. Любые вычисления (доли, разницы, средние) делай через calculator.
                - Независимые запросы к данным можно делать параллельно в одном ходе.

                Формат ответа: ключевые цифры, таблица в Markdown и 2–4 предложения интерпретации.
                """),
        };

        var workers = new[] { researcher, analyst };

        var planner = new AgentDefinition
        {
            Id = "planner",
            DisplayName = "Планировщик",
            Description = "разбивает запрос на шаги и распределяет их между исполнителями",
            JsonOutput = true,
            MaxIterations = 1,
            Instructions = Prompt("planner", date, $$"""
                Ты — агент-планировщик в команде ИИ-агентов компании «{{CompanyName}}». Разбей запрос пользователя на шаги и назначь каждый шаг исполнителю.

                Исполнители:
                {{string.Join("\n", workers.Select(w => $"- {w.Id} — {w.Description}"))}}

                Правила:
                1. Используй только перечисленных исполнителей. Не более {{options.MaxPlanSteps}} шагов; простой вопрос — 1 шаг. Обычно хватает 1–3 шагов.
                2. Шаги без зависимостей выполняются параллельно — это быстрее. Предпочитай независимые шаги:
                   исследователю можно сразу поручить найти причины, тренды и риски по теме, не дожидаясь цифр аналитика.
                   Указывай dependsOn, только если без результата другого шага задачу невозможно сформулировать.
                3. Каждая задача должна быть конкретной и понятной без контекста (исполнитель не видит других задач).
                4. Выводы и рекомендации пишет редактор после всех шагов — не создавай для них отдельный шаг.
                5. Если запрос не требует данных компании (приветствие, вопрос о твоих возможностях), верни пустой список steps.
                6. Учитывай историю диалога, если вопрос уточняющий.

                Ответь ТОЛЬКО JSON без пояснений:
                {"goal": "цель одним предложением", "steps": [{"id": "s1", "agent": "researcher", "task": "...", "dependsOn": []}]}
                """),
        };

        var writer = new AgentDefinition
        {
            Id = "writer",
            DisplayName = "Редактор",
            Description = "составляет итоговый ответ пользователю",
            MaxIterations = 1,
            Instructions = Prompt("writer", date, $"""
                Ты — редактор, который пишет итоговый ответ пользователю от имени ИИ-ассистента компании «{CompanyName}».

                Правила:
                - Используй только факты и цифры из результатов исполнителей. Не добавляй ничего от себя.
                - Пиши по-русски, структурированно, в Markdown: заголовки, списки, таблицы, где уместно.
                - Указывай источники фактов из базы знаний в квадратных скобках точно как в результатах исполнителей: [документ › раздел].
                  Цифры из данных продаж помечай как [данные продаж]. Не придумывай другие обозначения источников.
                - Если запрос подразумевает решение, заверши ответ разделом «Рекомендации»: 3–5 конкретных действий,
                  каждое опирается на цифру или факт из результатов (а не общие советы вроде «оптимизировать цены»).
                  Учитывай и рост, и падение показателей, и риски.
                - Если есть замечания критика — перепиши предыдущий черновик, устранив каждое замечание.
                - Сразу переходи к сути: без заголовка «Итоговый ответ», без вступлений и без заключительных фраз вроде «обращайтесь».
                - Не упоминай внутреннее устройство системы (агентов, шаги, критика).
                - Если исполнители не привлекались, ответь кратко и дружелюбно, расскажи, чем можешь помочь.
                """),
        };

        var critic = new AgentDefinition
        {
            Id = "critic",
            DisplayName = "Критик",
            Description = "проверяет черновик на полноту и фактическую точность",
            JsonOutput = true,
            MaxIterations = 1,
            Instructions = Prompt("critic", date, """
                Ты — строгий критик-рецензент. Проверь черновик ответа по критериям:
                1. Полнота: отвечает ли он на все части запроса пользователя.
                2. Точность: каждое число и факт подтверждены результатами исполнителей (никаких галлюцинаций).
                   Проверь причинно-следственные связи и периоды: не выдана ли возможность или прогноз на будущее за причину прошлых результатов.
                3. Ясность и структура.
                4. Практическая ценность: рекомендации конкретны и опираются на цифры и факты, а не являются общими советами.

                Перечисли в issues каждую найденную проблему. Если проблемы есть — approved = false.

                Одобряй (approved = true), только если score ≥ 8 и нет фактических ошибок.
                Ответь ТОЛЬКО JSON без пояснений:
                {"approved": true, "score": 8, "issues": ["конкретная проблема"], "feedback": "что именно исправить"}
                """),
        };

        return new AgentCatalog(planner, writer, critic, workers);
    }

    private static string Prompt(string agentId, string date, string body) =>
        new StringBuilder(body.Trim())
            .AppendLine()
            .AppendLine()
            .AppendLine($"Текущая дата: {date}.")
            .Append($"{CrewMarkers.AgentId} {agentId}")
            .ToString();
}
